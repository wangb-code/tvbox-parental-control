# 单韵母呼读音
FINAL_SOUND = {"a": "啊", "o": "喔", "e": "鹅", "i": "衣", "u": "乌", "ü": "鱼"}


def all_syllables():
    """列出所有 (音节key, 声调, 带调拼音, 同音字)。"""
    out = []
    for key, tones in SYLLABLE.items():
        for tone, (py, hanzi) in tones.items():
            out.append((key, tone, py, hanzi))
    return out


def by_pinyin(py):
    """按带调拼音反查 (key, tone, hanzi)。"""
    for key, tones in SYLLABLE.items():
        for tone, (p, hanzi) in tones.items():
            if p == py:
                return key, tone, hanzi
    return None



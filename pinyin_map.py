    items = all_syllables()
    print("音节条目:", len(items))
    print("声母数:", len(INITIAL_SOUND), "单韵母数:", len(FINAL_SOUND))
    # 同音字合法性粗校验：每个 hanzi 必须是单个汉字
    bad = [(py, hz) for _, _, py, hz in items if len(hz) != 1 or not ('\u4e00' <= hz <= '\u9fff')]
    print("非单汉字条目:", bad or "无")
